    def _generate_file_structure(self, file_path: str) -> str:
        """Generate structure diagram for file (all languages)"""
        try:
            abs_path = self.project_path / file_path
            if not abs_path.exists():
                return ""

            # Detect language
            language = abs_path.suffix.lower()

            # Try Python AST first
            if language == '.py':
                try:
                    with open(abs_path, 'r', encoding='utf-8') as f:
                        tree = ast.parse(f.read())

                    structure = "## 🏗️ Code Structure\n\n"

                    # Classes
                    classes = [n for n in ast.walk(tree) if isinstance(n, ast.ClassDef)]
                    if classes:
                        structure += "### Classes\n\n"
                        for cls in classes:
                            structure += f"#### `{cls.name}`\n\n"
                            methods = [n for n in cls.body if isinstance(n, ast.FunctionDef)]
                            if methods:
                                structure += "**Methods:**\n"
                                for method in methods:
                                    args = ', '.join([a.arg for a in method.args.args])
                                    structure += f"- `{method.name}({args})`\n"
                            structure += "\n"

                    # Functions
                    functions = [n for n in tree.body if isinstance(n, ast.FunctionDef)]
                    if functions:
                        structure += "### Functions\n\n"
                        for func in functions:
                            args = ', '.join([a.arg for a in func.args.args])
                            docstring = ast.get_docstring(func)
                            structure += f"#### `{func.name}({args})`\n\n"
                            if docstring:
                                structure += f"{docstring.split(chr(10))[0]}\n\n"

                    return structure
                except:
                    pass

            # Universal structure analysis for all languages
            return self._generate_universal_structure(abs_path)

        except:
            return ""

    def _generate_universal_structure(self, file_path: Path) -> str:
        """Generate detailed structure for any language"""
        try:
            with open(file_path, 'r', encoding='utf-8', errors='ignore') as f:
                content = f.read()
                lines = content.split('\n')

            structure = "## 🏗️ Code Structure\n\n"
            import re

            # Detect language
            ext = file_path.suffix.lower()
            language_map = {
                '.js': 'JavaScript', '.jsx': 'JavaScript',
                '.ts': 'TypeScript', '.tsx': 'TypeScript',
                '.java': 'Java', '.cpp': 'C++', '.c': 'C',
                '.cs': 'C#', '.go': 'Go', '.rs': 'Rust',
                '.rb': 'Ruby', '.php': 'PHP', '.swift': 'Swift', '.kt': 'Kotlin'
            }
            language = language_map.get(ext, 'Unknown')

            structure += f"**Language:** {language}\n\n"

            # Find imports/dependencies
            imports = self._extract_imports(content, ext)
            if imports:
                structure += "### 📦 Dependencies\n\n"
                for imp in imports[:10]:
                    structure += f"- `{imp}`\n"
                structure += "\n"

            # Find class definitions with details
            class_details = self._extract_classes(content, ext)
            if class_details:
                structure += "### 📋 Classes/Structures\n\n"
                for cls in class_details[:10]:
                    structure += f"#### `{cls['name']}`\n\n"
                    if cls.get('extends'):
                        structure += f"- **Extends:** `{cls['extends']}`\n"
                    if cls.get('methods'):
                        structure += f"- **Methods:** {len(cls['methods'])}\n"
                        for method in cls['methods'][:5]:
                            structure += f"  - `{method}()`\n"
                    structure += "\n"

            # Find function definitions with signatures
            functions = self._extract_functions(content, ext)
            if functions:
                structure += "### 🔧 Functions/Methods\n\n"
                for func in functions[:15]:
                    structure += f"#### `{func['name']}({func['params']})`\n\n"
                    if func.get('return_type'):
                        structure += f"**Returns:** `{func['return_type']}`\n\n"
                    if func.get('description'):
                        structure += f"{func['description']}\n\n"

            # Find constants/variables
            constants = self._extract_constants(content, ext)
            if constants:
                structure += "### 📌 Constants/Variables\n\n"
                for const in constants[:10]:
                    structure += f"- `{const}`\n"
                structure += "\n"

            # Add code statistics
            structure += "### 📊 Code Statistics\n\n"
            structure += f"- **Total Lines:** {len(lines)}\n"
            structure += f"- **Code Lines:** {len([l for l in lines if l.strip() and not l.strip().startswith(('//','#','/*','*'))])}\n"
            structure += f"- **Functions:** {len(functions)}\n"
            structure += f"- **Classes:** {len(class_details)}\n"
            structure += "\n"

            return structure if len(structure) > 100 else ""

        except Exception as e:
            return ""

    def _extract_imports(self, content: str, ext: str) -> list:
        """Extract import/require statements"""
        import re
        imports = []

        patterns = {
            '.js': [r'import\s+.*?from\s+[\'"](.+?)[\'"]', r'require\([\'"](.+?)[\'"]\)'],
            '.ts': [r'import\s+.*?from\s+[\'"](.+?)[\'"]', r'require\([\'"](.+?)[\'"]\)'],
            '.jsx': [r'import\s+.*?from\s+[\'"](.+?)[\'"]'],
            '.tsx': [r'import\s+.*?from\s+[\'"](.+?)[\'"]'],
            '.java': [r'import\s+([\w.]+);'],
            '.go': [r'import\s+"(.+?)"', r'import\s+\((.*?)\)'],
            '.rs': [r'use\s+([\w:]+);'],
            '.rb': [r'require\s+[\'"](.+?)[\'"]'],
            '.php': [r'use\s+([\w\\]+);', r'require\s+[\'"](.+?)[\'"]'],
            '.swift': [r'import\s+(\w+)'],
            '.kt': [r'import\s+([\w.]+)'],
            '.cs': [r'using\s+([\w.]+);'],
            '.cpp': [r'#include\s+[<"](.+?)[>"]'],
            '.c': [r'#include\s+[<"](.+?)[>"]'],
        }

        for pattern in patterns.get(ext, []):
            matches = re.findall(pattern, content, re.MULTILINE | re.DOTALL)
            imports.extend(matches)

        return list(set(imports))[:10]

    def _extract_classes(self, content: str, ext: str) -> list:
        """Extract class definitions with methods"""
        import re
        classes = []

        # Class pattern with optional extends/implements
        class_patterns = {
            '.js': r'class\s+(\w+)(?:\s+extends\s+(\w+))?',
            '.ts': r'(?:export\s+)?class\s+(\w+)(?:\s+extends\s+(\w+))?',
            '.jsx': r'class\s+(\w+)(?:\s+extends\s+(\w+))?',
            '.tsx': r'(?:export\s+)?class\s+(\w+)(?:\s+extends\s+(\w+))?',
            '.java': r'(?:public|private|protected)?\s+class\s+(\w+)(?:\s+extends\s+(\w+))?',
            '.cs': r'(?:public|private|protected)?\s+class\s+(\w+)(?:\s*:\s*(\w+))?',
            '.cpp': r'class\s+(\w+)(?:\s*:\s*(?:public|private|protected)\s+(\w+))?',
            '.swift': r'class\s+(\w+)(?:\s*:\s*(\w+))?',
            '.kt': r'class\s+(\w+)(?:\s*:\s*(\w+))?',
            '.rb': r'class\s+(\w+)(?:\s*<\s*(\w+))?',
            '.php': r'class\s+(\w+)(?:\s+extends\s+(\w+))?',
        }

        pattern = class_patterns.get(ext)
        if pattern:
            matches = re.findall(pattern, content)
            for match in matches:
                class_name = match[0] if isinstance(match, tuple) else match
                extends = match[1] if isinstance(match, tuple) and len(match) > 1 and match[1] else None

                # Find methods in this class
                methods = self._find_methods_in_class(content, class_name, ext)

                classes.append({
                    'name': class_name,
                    'extends': extends,
                    'methods': methods
                })

        return classes

    def _find_methods_in_class(self, content: str, class_name: str, ext: str) -> list:
        """Find methods within a class"""
        import re
        methods = []

        # Simple method detection (can be improved)
        method_patterns = {
            '.js': r'^\s+(\w+)\s*\(',
            '.ts': r'^\s+(?:public|private|protected)?\s*(\w+)\s*\(',
            '.jsx': r'^\s+(\w+)\s*\(',
            '.tsx': r'^\s+(?:public|private|protected)?\s*(\w+)\s*\(',
            '.java': r'^\s+(?:public|private|protected)\s+\w+\s+(\w+)\s*\(',
            '.cs': r'^\s+(?:public|private|protected)\s+\w+\s+(\w+)\s*\(',
            '.cpp': r'^\s+\w+\s+(\w+)\s*\(',
            '.swift': r'^\s+func\s+(\w+)\s*\(',
            '.kt': r'^\s+fun\s+(\w+)\s*\(',
            '.rb': r'^\s+def\s+(\w+)',
            '.php': r'^\s+(?:public|private|protected)?\s+function\s+(\w+)\s*\(',
        }

        pattern = method_patterns.get(ext)
        if pattern:
            matches = re.findall(pattern, content, re.MULTILINE)
            methods = list(set(matches))[:10]

        return methods

    def _extract_functions(self, content: str, ext: str) -> list:
        """Extract function definitions with details"""
        import re
        functions = []

        func_patterns = {
            '.js': r'(?:function|const|let|var)\s+(\w+)\s*=?\s*(?:async\s*)?\(([^)]*)\)\s*(?:=>|{)',
            '.ts': r'(?:function|const|let)\s+(\w+)\s*(?:<[^>]+>)?\s*\(([^)]*)\)\s*:\s*(\w+)',
            '.jsx': r'(?:function|const)\s+(\w+)\s*\(([^)]*)\)',
            '.tsx': r'(?:function|const)\s+(\w+)\s*(?:<[^>]+>)?\s*\(([^)]*)\)',
            '.java': r'(?:public|private|protected)\s+(?:static\s+)?(\w+)\s+(\w+)\s*\(([^)]*)\)',
            '.cs': r'(?:public|private|protected)\s+(?:static\s+)?(\w+)\s+(\w+)\s*\(([^)]*)\)',
            '.go': r'func\s+(\w+)\s*\(([^)]*)\)(?:\s*\(([^)]*)\))?',
            '.rs': r'fn\s+(\w+)\s*\(([^)]*)\)(?:\s*->\s*(\w+))?',
            '.swift': r'func\s+(\w+)\s*\(([^)]*)\)(?:\s*->\s*(\w+))?',
            '.kt': r'fun\s+(\w+)\s*\(([^)]*)\)(?:\s*:\s*(\w+))?',
            '.rb': r'def\s+(\w+)\s*(?:\(([^)]*)\))?',
            '.php': r'function\s+(\w+)\s*\(([^)]*)\)',
            '.cpp': r'(\w+)\s+(\w+)\s*\(([^)]*)\)',
            '.c': r'(\w+)\s+(\w+)\s*\(([^)]*)\)',
        }

        pattern = func_patterns.get(ext)
        if pattern:
            matches = re.findall(pattern, content)
            for match in matches[:15]:
                if isinstance(match, tuple):
                    if ext in ['.java', '.cs', '.cpp', '.c']:
                        func_name = match[1] if len(match) > 1 else match[0]
                        params = match[2] if len(match) > 2 else match[1] if len(match) > 1 else ''
                        return_type = match[0] if len(match) > 2 else None
                    else:
                        func_name = match[0]
                        params = match[1] if len(match) > 1 else ''
                        return_type = match[2] if len(match) > 2 else None
                else:
                    func_name = match
                    params = ''
                    return_type = None

                functions.append({
                    'name': func_name,
                    'params': params.strip() if params else '',
                    'return_type': return_type.strip() if return_type else None,
                    'description': ''
                })

        return functions

    def _extract_constants(self, content: str, ext: str) -> list:
        """Extract constants and global variables"""
        import re
        constants = []

        const_patterns = {
            '.js': r'(?:const|let|var)\s+([A-Z_][A-Z0-9_]*)\s*=',
            '.ts': r'(?:const|let)\s+([A-Z_][A-Z0-9_]*)\s*(?::\s*\w+)?\s*=',
            '.jsx': r'const\s+([A-Z_][A-Z0-9_]*)\s*=',
            '.tsx': r'const\s+([A-Z_][A-Z0-9_]*)\s*=',
            '.java': r'(?:public|private|protected)\s+static\s+final\s+\w+\s+([A-Z_][A-Z0-9_]*)',
            '.cs': r'(?:public|private|protected)\s+const\s+\w+\s+([A-Z_][A-Z0-9_]*)',
            '.go': r'const\s+([A-Z]\w*)',
            '.rs': r'const\s+([A-Z_][A-Z0-9_]*)',
            '.swift': r'let\s+([A-Z_][A-Z0-9_]*)',
            '.kt': r'const\s+val\s+([A-Z_][A-Z0-9_]*)',
            '.rb': r'([A-Z_][A-Z0-9_]*)\s*=',
            '.php': r'define\([\'"]([A-Z_][A-Z0-9_]*)[\'"]',
            '.cpp': r'#define\s+([A-Z_][A-Z0-9_]*)',
            '.c': r'#define\s+([A-Z_][A-Z0-9_]*)',
        }

        pattern = const_patterns.get(ext)
        if pattern:
            matches = re.findall(pattern, content)
            constants = list(set(matches))[:10]

        return constants

    def _generate_file_flow(self, file_path: str) -> str:
        """Generate flow diagram for file (all languages)"""
        try:
            abs_path = self.project_path / file_path
            if not abs_path.exists():
                return ""

            language = abs_path.suffix.lower()

            # Try Python AST first
            if language == '.py':
                try:
                    with open(abs_path, 'r', encoding='utf-8') as f:
                        tree = ast.parse(f.read())

                    functions = [n.name for n in ast.walk(tree) if isinstance(n, ast.FunctionDef)][:10]

                    if not functions:
                        return ""

                    flow = "## 🔄 Function Flow\n\n```mermaid\ngraph TD\n"
                    flow += "    Start[Module Load]\n"

                    for i, func in enumerate(functions):
                        flow += f"    Start --> F{i}[{func}()]\n"

                    flow += "```"

                    return flow
                except:
                    pass

            # Universal flow for all languages
            return self._generate_universal_flow(abs_path)

        except:
            return ""

    def _generate_universal_flow(self, file_path: Path) -> str:
        """Generate basic flow diagram for any language"""
        try:
            with open(file_path, 'r', encoding='utf-8', errors='ignore') as f:
                content = f.read()

            import re

            # Find function names using universal patterns
            func_patterns = [
                r'function\s+(\w+)',
                r'def\s+(\w+)',
                r'func\s+(\w+)',
                r'fn\s+(\w+)',
                r'(?:public|private|protected)?\s+\w+\s+(\w+)\s*\(',
            ]

            functions = set()
            for pattern in func_patterns:
                functions.update(re.findall(pattern, content))

            functions = list(functions)[:10]

            if not functions:
                return ""

            flow = "## 🔄 Code Flow\n\n```mermaid\ngraph TD\n"
            flow += "    Start[File Entry]\n"

            for i, func in enumerate(functions):
                flow += f"    Start --> F{i}[{func}()]\n"

            flow += "```"

            return flow

        except:
            return ""

    def _generate_pie_chart_data(self, lang_stats: Dict) -> str:
        """Generate pie chart data for mermaid"""
        lines = []
        for lang, stats in lang_stats.items():
            lines.append(f'    "{lang}" : {stats["code"]}')
        return '\n'.join(lines)

    def _get_badge_color(self, score: float) -> str:
        """Get badge color based on score"""
        if score >= 90:
            return 'brightgreen'
        elif score >= 80:
            return 'green'
        elif score >= 70:
            return 'yellowgreen'
        elif score >= 60:
            return 'yellow'
        else:
            return 'red'


