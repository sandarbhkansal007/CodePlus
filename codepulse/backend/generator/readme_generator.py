    def _generate_module_docs(self) -> str:
        """Generate module documentation"""
        files = self.file_metrics.get('files', [])

        module_docs = "## 📚 Module Documentation\n\n"

        # Group by directory
        python_files = [f for f in files if f['language'] == 'Python'][:10]

        for file_info in python_files:
            path = file_info['path']
            lines = file_info['lines']['code']

            module_docs += f"### `{path}`\n\n"
            module_docs += f"- **Lines:** {lines}\n"
            module_docs += f"- **Language:** {file_info['language']}\n"

            # Try to parse and extract info
            try:
                abs_path = self.project_path / path
                if abs_path.exists():
                    with open(abs_path, 'r', encoding='utf-8') as f:
                        content = f.read()
                        tree = ast.parse(content)

                        # Extract docstring
                        docstring = ast.get_docstring(tree)
                        if docstring:
                            module_docs += f"- **Description:** {docstring.split(chr(10))[0]}\n"

                        # Count functions
                        functions = [n for n in ast.walk(tree) if isinstance(n, ast.FunctionDef)]
                        if functions:
                            module_docs += f"- **Functions:** {len(functions)}\n"
                            func_list = ', '.join([f.name for f in functions[:5]])
                            module_docs += f"  - {func_list}\n"

                        # Count classes
                        classes = [n for n in ast.walk(tree) if isinstance(n, ast.ClassDef)]
                        if classes:
                            module_docs += f"- **Classes:** {len(classes)}\n"
                            class_list = ', '.join([c.name for c in classes[:5]])
                            module_docs += f"  - {class_list}\n"
            except:
                pass

            module_docs += "\n"

        return module_docs

