"""
README Generator - Generates comprehensive documentation with code flow diagrams
"""

from typing import Dict, List, Optional
from pathlib import Path
import ast


class ReadmeGenerator:
    """Generates README.md with code structure and flow diagrams"""

    def __init__(self, project_path: str, analysis_results: Dict):
        """
        Initialize README Generator

        Args:
            project_path: Path to the project
            analysis_results: Complete analysis results from CodePulseAnalyzer
        """
        self.project_path = Path(project_path)
        self.results = analysis_results
        self.file_metrics = analysis_results.get('file_metrics', {})
        self.health = analysis_results.get('health', {})
        self.personality = analysis_results.get('personality', {})

    def generate_full_readme(self) -> str:
        """
        Generate complete README with all sections

        Returns:
            Complete README markdown
        """
        sections = []

        # Header
        sections.append(self._generate_header())

        # Overview
        sections.append(self._generate_overview())

        # Health & Quality
        sections.append(self._generate_health_section())

        # Architecture
        sections.append(self._generate_architecture())

        # Project Structure
        sections.append(self._generate_structure())

        # Code Flow Diagrams
        sections.append(self._generate_flow_diagrams())

        # Module Documentation
        sections.append(self._generate_module_docs())

        # Getting Started
        sections.append(self._generate_getting_started())

        # Contributing
        sections.append(self._generate_contributing())

        return '\n\n'.join(sections)

    def generate_file_readme(self, file_path: str) -> str:
        """
        Generate README for a specific file

        Args:
            file_path: Relative path to file

        Returns:
            File-specific README
        """
        sections = []

        # Header
        sections.append(f"# 📄 {Path(file_path).name}")
        sections.append(f"**File:** `{file_path}`")

        # File analysis
        sections.append(self._generate_file_analysis(file_path))

        # Code structure
        sections.append(self._generate_file_structure(file_path))

        # Function flow
        sections.append(self._generate_file_flow(file_path))

        return '\n\n'.join(sections)

    def _generate_header(self) -> str:
        """Generate README header"""
        project_name = self.project_path.name.replace('_', ' ').replace('-', ' ').title()

        return f"""# {project_name}

> 📊 Generated by [CodePulse](https://github.com/yourusername/codepulse)
>
> 📅 Generated: {self.results.get('analysis_timestamp', 'N/A')[:10]}

[![Health Score](https://img.shields.io/badge/Health_Score-{self.health.get('overall_score', 0):.0f}%25-{self._get_badge_color(self.health.get('overall_score', 0))})](https://github.com)
[![Code Lines](https://img.shields.io/badge/Code_Lines-{self.file_metrics.get('code_lines', 0):,}-blue)](https://github.com)
[![Files](https://img.shields.io/badge/Files-{self.file_metrics.get('total_files', 0)}-green)](https://github.com)"""

    def _generate_overview(self) -> str:
        """Generate project overview"""
        personality = self.personality.get('personality', 'Unknown')
        description = self.personality.get('description', '')

        return f"""## 📋 Overview

**Project Type:** {personality}

{description}

### Quick Stats

| Metric | Value |
|--------|-------|
| **Health Score** | {self.health.get('overall_score', 0):.1f}/100 ({self.health.get('rating', 'N/A').upper()}) |
| **Total Files** | {self.file_metrics.get('total_files', 0)} |
| **Lines of Code** | {self.file_metrics.get('code_lines', 0):,} |
| **Languages** | {', '.join(self.file_metrics.get('language_stats', {}).keys())} |
| **Personality** | {personality} |"""

    def _generate_health_section(self) -> str:
        """Generate health & quality section"""
        components = self.health.get('components', {})

        bars = []
        for name, data in components.items():
            score = data.get('score', 0)
            filled = int(score / 5)
            bar = '█' * filled + '░' * (20 - filled)
            bars.append(f"**{name.replace('_', ' ').title()}**: `{bar}` {score:.1f}/100")

        health_bars = '\n'.join(bars)

        insights = self.results.get('insights', [])
        insight_list = '\n'.join([f"- {insight}" for insight in insights[:5]])

        return f"""## 💊 Code Health

### Health Components

{health_bars}

### Key Insights

{insight_list}"""

    def _generate_architecture(self) -> str:
        """Generate architecture diagram"""
        lang_stats = self.file_metrics.get('language_stats', {})

        # Create directory structure diagram
        files = self.file_metrics.get('files', [])

        # Build tree
        tree_lines = []
        dirs = {}
        for file_info in files:
            path = Path(file_info['path'])
            if len(path.parts) > 1:
                dir_name = path.parts[0]
                if dir_name not in dirs:
                    dirs[dir_name] = []
                dirs[dir_name].append(path.name)

        # Create mermaid diagram
        mermaid_graph = """```mermaid
graph TD
    Root[Project Root]
"""

        for i, (dir_name, files_in_dir) in enumerate(dirs.items()):
            mermaid_graph += f"    Root --> Dir{i}[{dir_name}/]\n"
            for j, file in enumerate(files_in_dir[:5]):  # Limit to 5 files per dir
                mermaid_graph += f"    Dir{i} --> File{i}_{j}[{file}]\n"
            if len(files_in_dir) > 5:
                mermaid_graph += f"    Dir{i} --> More{i}[...{len(files_in_dir) - 5} more]\n"

        mermaid_graph += "```"

        return f"""## 🏗️ Architecture

### Project Structure

{mermaid_graph}

### Language Distribution

```mermaid
pie title "Code Distribution"
{self._generate_pie_chart_data(lang_stats)}
```"""

    def _generate_structure(self) -> str:
        """Generate project structure tree"""
        files = self.file_metrics.get('files', [])

        # Build tree structure
        tree = "```\n"
        tree += f"{self.project_path.name}/\n"

        # Group by directory
        dirs = {}
        for file_info in files[:30]:  # Limit to 30 files
            path = Path(file_info['path'])
            if len(path.parts) > 1:
                dir_name = str(path.parent)
                if dir_name not in dirs:
                    dirs[dir_name] = []
                dirs[dir_name].append({
                    'name': path.name,
                    'lines': file_info['lines']['code'],
                    'language': file_info['language']
                })
            else:
                if '.' not in dirs:
                    dirs['.'] = []
                dirs['.'].append({
                    'name': path.name,
                    'lines': file_info['lines']['code'],
                    'language': file_info['language']
                })

        # Print tree
        for dir_name in sorted(dirs.keys()):
            if dir_name != '.':
                tree += f"├── {dir_name}/\n"
                for file_info in dirs[dir_name]:
                    tree += f"│   ├── {file_info['name']} ({file_info['lines']} lines, {file_info['language']})\n"

        # Root files
        if '.' in dirs:
            for file_info in dirs['.']:
                tree += f"├── {file_info['name']} ({file_info['lines']} lines, {file_info['language']})\n"

        tree += "```"

        return f"""## 📁 Project Structure

{tree}

**Total:** {self.file_metrics.get('total_files', 0)} files, {self.file_metrics.get('code_lines', 0):,} lines of code"""

